; ЛР №3, задание 2, сложный уровень, вариант 1.
; Программа, вызывающая access1 из hard.a с параметрами, проходящими
; внутреннюю проверку (должна напечатать "Access granted").
;
; Восстановленная сигнатура (см. lab3_task2_restored_code.md для разбора):
;   namespace hard { namespace var1 {
;       struct S { char data[/* размер не важен для вызова */]; };
;       class C {
;           int field;
;       public:
;           bool check(const S& s) const;
;       };
;       extern "C" void access1(C a, const S& b);
;   }}
;
; access1 устроен так:
;   - если a.field == 0, сразу печатает "Access denied" и завершает программу;
;   - иначе вызывает a.check(b) и печатает результат через check(bool).
;
; check(const S& s) считает по байтам s.data (до первого нулевого байта)
; 4-байтный аккумулятор: cell[i mod 4] = ~(cell[i mod 4] ^ data[i]),
; и сравнивает получившееся 4-байтное число с полем a.field.
;
; Подобранные значения: data = {1, 0} (один байт 1, затем терминатор).
; Тогда обрабатывается только data[0]=1: cell[0] = ~1 = 0xFE = 254,
; остальные ячейки остаются 0 (обнулены изначально). Итоговый аккумулятор
; = 0x000000FE = 254. Значит C.field = 254 одновременно удовлетворяет
; и проверке "field != 0", и равенству аккумулятору.
;
; Соглашение Microsoft x64 (как и в прошлых лабах через SASM/MinGW):
;   C a передаётся по значению в ECX (структура из одного int умещается
;   в регистр); const S& b передаётся как указатель в RDX.
;
; ПРИМЕЧАНИЕ: не компилировалось и не линковалось с hard.a (нет NASM/MinGW
; в среде, где это писалось). Восстановленная логика проверена только
; чтением дизассемблированного кода библиотеки, без реального запуска.

section .data
    s_data: db 1, 0        ; S.data = {1, 0}: один содержательный байт + терминатор

section .text
    extern access1
    global main

main:
    push rbp
    mov rbp, rsp
    sub rsp, 32            ; теневое пространство для вызова access1

    mov ecx, 254           ; C a = { field = 254 }  (POD <= 8 байт -> в регистре ECX)
    lea rdx, [s_data]      ; const S& b = &s_data

    call access1           ; должна напечатать "Access granted"

    xor eax, eax
    mov rsp, rbp
    pop rbp
    ret
